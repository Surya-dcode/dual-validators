"""Copy spec/invariants.json into both packages.

The browser cannot read a file next to the page, and an installed Python
package cannot see the repository root, so each implementation embeds its own
copy of the spec. This script writes those copies. With --check it writes
nothing and exits 1 if either copy is out of date.

    python scripts/sync_spec.py          # rewrite both copies
    python scripts/sync_spec.py --check  # CI mode
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec" / "invariants.json"
PY_COPY = ROOT / "src" / "dualval" / "invariants.json"
JS_COPY = ROOT / "js" / "src" / "spec.js"

JS_HEADER = (
    "// Generated by scripts/sync_spec.py from spec/invariants.json. Do not edit by hand.\n"
    "// Run `python scripts/sync_spec.py` after changing the spec.\n"
)


def expected_outputs() -> dict[Path, str]:
    text = SPEC.read_text(encoding="utf-8")
    data = json.loads(text)
    js_body = json.dumps(data, indent=2, ensure_ascii=False)
    return {
        PY_COPY: text,
        JS_COPY: f"{JS_HEADER}\nexport const SPEC = Object.freeze({js_body});\n",
    }


def stale_copies() -> list[Path]:
    stale = []
    for path, content in expected_outputs().items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path)
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a copy is stale")
    args = parser.parse_args(argv)

    if args.check:
        stale = stale_copies()
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run python scripts/sync_spec.py)")
        if not stale:
            print("sync_spec: both embedded copies match spec/invariants.json")
        return 1 if stale else 0

    for path, content in expected_outputs().items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
